#!/usr/bin/env node
/**
 * Подставляет данные клиента в сборку.
 * Использование: node scripts/prepare-client.mjs <slug>
 * Или: npm run prepare:client -- <slug>
 */
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const currentFile = path.join(root, 'clients', '.current')

function resolveSlug() {
  const arg = process.argv[2] || process.env.CLIENT
  if (arg) {
    fs.writeFileSync(currentFile, arg + '\n')
    return arg
  }
  if (fs.existsSync(currentFile)) {
    return fs.readFileSync(currentFile, 'utf8').trim() || 'sgx'
  }
  return 'sgx'
}

const slug = resolveSlug()
const clientDir = path.join(root, 'clients', slug)

function fail(msg) {
  console.error(`prepare-client: ${msg}`)
  process.exit(1)
}

if (!fs.existsSync(path.join(clientDir, 'client.json'))) {
  fail(`нет clients/${slug}/client.json`)
}

let client
try {
  client = JSON.parse(fs.readFileSync(path.join(clientDir, 'client.json'), 'utf8'))
} catch (e) {
  fail(`client.json не парсится: ${e.message}`)
}

const brand = client.brand || {}
const studio = client.studio || {}
const workerName = client.workerName || `detailing-${slug}`

const requiredStudio = [
  'name',
  'tagline',
  'description',
  'address',
  'phone',
  'workHours',
  'logoUrl',
  'heroImageUrl',
  'services',
  'photos',
]
for (const key of requiredStudio) {
  if (studio[key] === undefined || studio[key] === null || studio[key] === '') {
    fail(`studio.${key} обязателен в clients/${slug}/client.json`)
  }
}
if (!Array.isArray(studio.services) || studio.services.length === 0) {
  fail('studio.services должен быть непустым массивом')
}
if (!brand.name || !brand.shortName) {
  fail('brand.name и brand.shortName обязательны')
}

// --- hash контента → DEFAULTS_REV (авто-обновление localStorage при правках) ---
const brandOut = {
  currency: '₽',
  ...brand,
}
const contentHash = createHash('sha256')
  .update(JSON.stringify({ brand: brandOut, studio, workerName, slug }))
  .digest('hex')
  .slice(0, 8)
const defaultsRev = parseInt(contentHash, 16) % 1_000_000_000

// --- src/data/client-data.ts ---
const studioWithId = {
  id: `studio-${slug}`,
  ...studio,
}
const ts = `// AUTO-GENERATED by scripts/prepare-client.mjs — do not edit.
// Source: clients/${slug}/client.json

export const CLIENT_SLUG = ${JSON.stringify(slug)}
export const CLIENT_WORKER = ${JSON.stringify(workerName)}
export const CLIENT_BRAND = ${JSON.stringify(brandOut, null, 2)} as const

export const DEFAULTS_REV = ${defaultsRev}

export const CLIENT_STUDIO = ${JSON.stringify(studioWithId, null, 2)} as const
`
fs.writeFileSync(path.join(root, 'src', 'data', 'client-data.ts'), ts)

// --- src/data/client-meta.json (для vite.config.ts / index.html) ---
const meta = {
  slug,
  workerName,
  name: brand.name,
  shortName: brand.shortName,
  description: brand.description || studio.tagline || brand.name,
  currency: brandOut.currency,
}
fs.writeFileSync(
  path.join(root, 'src', 'data', 'client-meta.json'),
  JSON.stringify(meta, null, 2) + '\n'
)

// --- public/assets: заменяем файлы клиента ---
const assetsSrc = path.join(clientDir, 'assets')
const assetsDst = path.join(root, 'public', 'assets')
if (!fs.existsSync(assetsSrc)) {
  fail(`нет папки clients/${slug}/assets`)
}
fs.mkdirSync(assetsDst, { recursive: true })
for (const f of fs.readdirSync(assetsDst)) {
  fs.rmSync(path.join(assetsDst, f), { force: true })
}
let assetCount = 0
for (const f of fs.readdirSync(assetsSrc)) {
  const src = path.join(assetsSrc, f)
  if (!fs.statSync(src).isFile()) continue
  fs.copyFileSync(src, path.join(assetsDst, f))
  assetCount++
}
if (assetCount === 0) fail(`clients/${slug}/assets пуста`)

// --- public/icons + favicon: PWA-иконки из логотипа клиента (если есть) ---
const iconsSrc = path.join(clientDir, 'icons')
const publicDir = path.join(root, 'public')
const iconsDst = path.join(publicDir, 'icons')
const iconFiles = [
  ['icons/icon-180.png', path.join(iconsDst, 'icon-180.png')],
  ['icons/icon-192.png', path.join(iconsDst, 'icon-192.png')],
  ['icons/icon-512.png', path.join(iconsDst, 'icon-512.png')],
  ['icons/maskable-512.png', path.join(iconsDst, 'maskable-512.png')],
  ['icons/startup-1170x2532.png', path.join(iconsDst, 'startup-1170x2532.png')],
  ['icons/startup-750x1334.png', path.join(iconsDst, 'startup-750x1334.png')],
  ['icons/icon-192.png', path.join(publicDir, 'icon-192.png')],
  ['icons/icon-512.png', path.join(publicDir, 'icon-512.png')],
  ['icons/favicon.svg', path.join(publicDir, 'favicon.svg')],
]
let iconCount = 0
if (fs.existsSync(iconsSrc)) {
  fs.mkdirSync(iconsDst, { recursive: true })
  for (const [rel, dst] of iconFiles) {
    const src = path.join(clientDir, rel)
    if (!fs.existsSync(src)) continue
    fs.copyFileSync(src, dst)
    iconCount++
  }
}
if (iconCount === 0) {
  console.log(`  icons: нет clients/${slug}/icons — оставляем текущие public/icons`)
} else {
  console.log(`  icons: ${iconCount} файлов из clients/${slug}/icons → public/`)
}

// проверим, что все imageUrl/logo из JSON есть в assets
const referenced = new Set()
const collect = (v) => {
  if (typeof v === 'string') {
    const m = v.match(/^\/assets\/(.+)$/)
    if (m) referenced.add(m[1])
  } else if (Array.isArray(v)) v.forEach(collect)
  else if (v && typeof v === 'object') Object.values(v).forEach(collect)
}
collect(studio)
for (const f of referenced) {
  if (!fs.existsSync(path.join(assetsDst, f))) {
    fail(`в client.json ссылка на /assets/${f}, но файла нет в clients/${slug}/assets/`)
  }
}

// --- index.html: title / description / apple-title ---
const indexHtmlPath = path.join(root, 'index.html')
let html = fs.readFileSync(indexHtmlPath, 'utf8')
html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${brand.name}</title>`)
html = html.replace(
  /(<meta name="apple-mobile-web-app-title" content=")[^"]*(")/,
  `$1${brand.shortName}$2`
)
html = html.replace(
  /(<meta\s+name="description"\s+content=")[^"]*(")/,
  `$1${meta.description}$2`
)
fs.writeFileSync(indexHtmlPath, html)

// --- wrangler.toml: имя worker → субдомен + своя D1 (name + id) ---
const databaseName = client.databaseName || `${workerName}-db`
const databaseId = client.databaseId || 'REPLACE_BY_SHIP'
const studioId = `studio-${slug}`
const wranglerPath = path.join(root, 'wrangler.toml')
let wrangler = fs.readFileSync(wranglerPath, 'utf8')
wrangler = wrangler.replace(/^name = ".*"$/m, `name = "${workerName}"`)
if (/^\[vars\]/m.test(wrangler)) {
  wrangler = wrangler.replace(/WORKER_NAME = ".*"/m, `WORKER_NAME = "${workerName}"`)
  if (/^STUDIO_ID = /m.test(wrangler)) {
    wrangler = wrangler.replace(/^STUDIO_ID = ".*"/m, `STUDIO_ID = "${studioId}"`)
  } else {
    wrangler = wrangler.replace(/^(WORKER_NAME = ".*")$/m, `$1\nSTUDIO_ID = "${studioId}"`)
  }
} else {
  wrangler += `\n[vars]\nWORKER_NAME = "${workerName}"\nSTUDIO_ID = "${studioId}"\n`
}
// database_name + database_id — своя D1 на клиента (id критичен: name можно переиспользовать)
if (/^\[\[d1_databases\]\]/m.test(wrangler)) {
  wrangler = wrangler.replace(/database_name = ".*"/m, `database_name = "${databaseName}"`)
  wrangler = wrangler.replace(/database_id = ".*"/m, `database_id = "${databaseId}"`)
}
fs.writeFileSync(wranglerPath, wrangler)

console.log(`prepare-client: ${slug}`)
console.log(`  brand: ${brand.name} (${brand.shortName})`)
console.log(`  worker: ${workerName} → https://${workerName}.deteiling-pro.workers.dev`)
console.log(`  D1: ${databaseName} (${databaseId})`)
console.log(`  assets: ${assetCount} файлов → public/assets`)
console.log(`  DEFAULTS_REV: ${defaultsRev}`)
